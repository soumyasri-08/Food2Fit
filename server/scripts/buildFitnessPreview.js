const fs = require('node:fs');
const path = require('node:path');
const { prepareProteinNap } = require('../seed/proteinNap');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'client/src/services/fitnessPreview');
function artifacts() {
  const constants = fs.readFileSync(path.join(__dirname, '../services/fitnessConstants.js'), 'utf8').replace(/module\.exports = .*;\s*$/, '');
  const engine = fs.readFileSync(path.join(__dirname, '../services/fitnessEngine.js'), 'utf8')
    .replace(/^const .* = require\([^\n]+\);\r?\n/gm, '')
    .replace('module.exports =', 'export');
  if (/require\(|module\.exports/.test(constants + engine)) throw new Error('Unexpected engine dependencies; update preview builder.');
  const header = '// Generated by server/scripts/buildFitnessPreview.js; edit the server engine and regenerate.\n';
  const errors = 'class AppError extends Error { constructor(status, code, message, details) { super(message); Object.assign(this, { status, code, details }); } }\n';
  const foods = prepareProteinNap().foods.map((f, i) => ({ ...f, _id: `protein-nap-${i + 1}` }));
  const exercises = require('../seed/data/exercises.json').map((e, i) => ({ ...e, _id: `exercise-${i + 1}` }));
  return {
    'engine.js': header + errors + constants + '\n' + engine,
    'data.json': JSON.stringify({ version: 'protein-nap-v1.1-selection-54-v1', foods, exercises }, null, 2) + '\n',
  };
}
if (require.main === module) {
  fs.mkdirSync(output, { recursive: true });
  for (const [file, content] of Object.entries(artifacts())) fs.writeFileSync(path.join(output, file), content);
  fs.mkdirSync(path.join(root, 'client/public'), { recursive: true });
  fs.copyFileSync(path.join(root, 'protein-nap-dataset/PROTEIN-NAP.md'), path.join(root, 'client/public/protein-nap-attribution.txt'));
  console.log('Built browser fitness engine, 54 PROTEIN NAP foods and 72 exercise-library records.');
}
module.exports = { artifacts, output };
